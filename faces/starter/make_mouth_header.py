#!/usr/bin/env python3
"""Build hg_mouth_frames.h from your own mouth pictures (CC0).

Input: a folder with 320x240 PNGs named <mood>_<viseme>.png, where
  mood   = neutral, sad, thinking, pet
  viseme = closed, half, open, wide_e, round_o, small_u, wide_i, smile (smile only for neutral)
Each PNG is the full face with that mouth. Outside the mouth box it must match frame 0 of
the matching GIF exactly, because only the box is copied.
Usage: python3 make_mouth_header.py FOLDER X Y W H > hg_mouth_frames.h
"""
import sys
from PIL import Image
VIS = ["closed", "half", "open", "wide_e", "round_o", "small_u", "wide_i", "smile"]
MOODS = ["neutral", "sad", "thinking", "pet"]
folder, x, y, w, h = sys.argv[1], *map(int, sys.argv[2:6])
def box(path):
    im = Image.open(path).convert("RGB")
    assert im.size == (320, 240), path + " must be 320x240"
    out = []
    for yy in range(y, y + h):
        for xx in range(x, x + w):
            r, g, b = im.getpixel((xx, yy))
            c = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
            out += [c & 0xFF, c >> 8]
    return out
print("// generated by make_mouth_header.py. Do not edit.\n#pragma once\n#include <stdint.h>\n#define HG_MOUTH_COUNT 8")
for m in MOODS:
    names = []
    for v in VIS:
        if v == "smile" and m != "neutral":
            names.append("hg_mouth_%s_closed" % m); continue
        d = box("%s/%s_%s.png" % (folder, m, v))
        print("static const uint8_t hg_mouth_%s_%s[%d] = {%s};" % (m, v, len(d), ",".join(map(str, d))))
        names.append("hg_mouth_%s_%s" % (m, v))
    print("static const uint8_t* const hg_mouth_%s[HG_MOUTH_COUNT] = {%s};" % (m, ",".join(names)))
print("struct HgMouthSet { const char* gif; int x, y, w, h; const uint8_t* const* frames; };")
print("static const HgMouthSet hg_mouth_sets[] = {")
for m in MOODS:
    print('    {"%s", %d, %d, %d, %d, hg_mouth_%s},' % (m, x, y, w, h, m))
print("};\n#define HG_MOUTH_SET_COUNT 4")
