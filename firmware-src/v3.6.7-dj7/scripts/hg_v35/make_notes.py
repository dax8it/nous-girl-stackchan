#!/usr/bin/env python3
"""Two music-note glyphs as LVGL A8 alpha masks (colored at runtime). Output: hg_notes.h"""
from PIL import Image, ImageDraw
import numpy as np
S = 6
def note8(w=20, h=26):
    im = Image.new('L', (w*S, h*S), 0); d = ImageDraw.Draw(im)
    # head (tilted ellipse), stem, flag
    head = Image.new('L', (int(9*S), int(6.5*S)), 0); ImageDraw.Draw(head).ellipse((0, 0, 9*S-1, 6.5*S-1), fill=255)
    head = head.rotate(25, expand=True, resample=Image.BICUBIC)
    im.paste(head, (int(0.5*S), int((h-8.5)*S)), head)
    d.rectangle((int(8.2*S), int(2*S), int(10*S), int((h-4.5)*S)), fill=255)
    d.polygon([(8.2*S, 2*S), (10*S, 2*S), (17*S, 8*S), (16*S, 13*S), (14.5*S, 9.5*S), (10*S, 6.5*S)], fill=255)
    return im.resize((w, h), Image.LANCZOS)
def note16(w=26, h=26):
    im = Image.new('L', (w*S, h*S), 0); d = ImageDraw.Draw(im)
    for hx in (0.5, 14.5):
        head = Image.new('L', (int(9*S), int(6.5*S)), 0); ImageDraw.Draw(head).ellipse((0, 0, 9*S-1, 6.5*S-1), fill=255)
        head = head.rotate(25, expand=True, resample=Image.BICUBIC)
        im.paste(head, (int(hx*S), int((h-8.5)*S)), head)
    d.rectangle((int(8.2*S), int(3*S), int(10*S), int((h-4.5)*S)), fill=255)
    d.rectangle((int(22.2*S), int(1*S), int(24*S), int((h-4.5)*S)), fill=255)
    d.polygon([(8.2*S, 3*S), (24*S, 1*S), (24*S, 5*S), (8.2*S, 7*S)], fill=255)
    return im.resize((w, h), Image.LANCZOS)
def anger(w=30, h=30):
    # manga anger mark: four brackets that bulge toward the middle
    im = Image.new('L', (w*S, h*S), 0); d = ImageDraw.Draw(im)
    r = int(12.5*S); t = int(3.6*S)
    for cx, cy, a0 in ((0, 0, 0), (w*S, 0, 90), (w*S, h*S, 180), (0, h*S, 270)):
        d.arc((cx-r, cy-r, cx+r, cy+r), a0+12, a0+78, fill=255, width=t)
    return im.resize((w, h), Image.LANCZOS)
notes = {'note8': note8(), 'note16': note16(), 'anger': anger()}
lines = ['// generated by make_notes.py (headphone-girl v3.5 party face). Do not edit.', '#pragma once', '#include <stdint.h>']
for n, im in notes.items():
    a = np.array(im)
    lines.append(f'#define HG_{n.upper()}_W {im.width}')
    lines.append(f'#define HG_{n.upper()}_H {im.height}')
    lines.append(f'static const uint8_t hg_{n}_a8[{a.size}] = {{{",".join(map(str, a.flatten()))}}};')
    im.save(f'{n}.png')
open('hg_notes.h', 'w').write('\n'.join(lines) + '\n')
print('ok', {n: im.size for n, im in notes.items()})
