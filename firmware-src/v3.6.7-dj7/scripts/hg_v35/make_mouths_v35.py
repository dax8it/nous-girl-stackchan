#!/usr/bin/env python3
"""headphone-girl v3.5 mouth frames, built from Alex's headphone-girl art.

Sets (one per talking face): neutral (also used for happy), sad, thinking, pet (loving).
Each set has 8 frames in this order:
  0 closed, 1 half, 2 open (A), 3 wide_e (E), 4 round_o (O), 5 small_u (U), 6 wide_i (I), 7 smile
Frames 0-5 of the neutral set are byte-identical to v3.4 (same recipe as make_mouths.py).
New shapes are warps of Alex's own open mouth (speaking_01) and smile (pet_00) strokes.
Output: hg_mouth_frames.h (RGB565 LE, opaque crops), previews in ./preview/.
"""
import numpy as np, json, os, sys
from PIL import Image, ImageFilter, ImageDraw
SRC = sys.argv[1] if len(sys.argv) > 1 else './your-face-frames'
OUT = sys.argv[2] if len(sys.argv) > 2 else '.'
L = lambda n: Image.open(f'{SRC}/{n}.png').convert('L')
N = L('neutral_00'); O = L('speaking_01'); P = L('pet_00')
W, H = 320, 240
ZX, ZY = np.meshgrid(np.arange(W), np.arange(H))
white = Image.new('L', (W, H), 255)
blur = lambda m: Image.fromarray((m * 255).astype(np.uint8)).filter(ImageFilter.GaussianBlur(0.6))

# ---- v3.4 recipe (neutral) ----
BOX0 = (84, 130, 124, 174); CX, CY = 102.0, 151.0
lx, ly = ZX - BOX0[0], ZY - BOX0[1]
zone0 = (((ZX - CX) / 13.0) ** 2 + ((ZY - CY) / 10.5) ** 2 <= 1.0) & (lx >= (ly - 12) * 15 / 32 + 2)
ZONE0 = blur(zone0)
def ink_dark(im):
    return im.point(lambda v: int(255 * ((v / 255.0) ** 1.8)))
def open_ink(sx, sy, bx=CX, by=CY):
    """Alex's open mouth, scaled around its center and moved to (bx, by). White elsewhere."""
    src = Image.composite(O, white, ZONE0)
    a = (1 / sx, 0, CX - bx / sx, 0, 1 / sy, CY - by / sy)
    return ink_dark(src.transform((W, H), Image.AFFINE, a, resample=Image.BICUBIC, fillcolor=255))
def put(base, zone_img, ink):
    cleared = Image.composite(white, base, zone_img)
    ink = Image.composite(ink, white, zone_img)
    return Image.fromarray(np.minimum(np.array(cleared), np.array(ink)))
# smile strokes from pet_00 (upturned line + small lower-lip mark)
pet_smile_mask = np.zeros((H, W), bool)
pet_smile_mask[139:150, 95:130] = True
pet_smile_mask[152:157, 100:111] = True
def smile_ink(sx, sy, bx, by, pcx=111.0, pcy=148.0):
    src = Image.composite(P, white, Image.fromarray((pet_smile_mask * 255).astype(np.uint8)))
    a = (1 / sx, 0, pcx - bx / sx, 0, 1 / sy, pcy - by / sy)
    return ink_dark(src.transform((W, H), Image.AFFINE, a, resample=Image.BICUBIC, fillcolor=255))

SHAPES = ['closed', 'half', 'open', 'wide_e', 'round_o', 'small_u', 'wide_i', 'smile']
SCALE = {'half': (1.0, 0.5), 'open': (1.0, 1.0), 'wide_e': (1.12, 0.42), 'round_o': (0.68, 1.0),
         'small_u': (0.6, 0.55), 'wide_i': (1.22, 0.26)}

def neutral_set():
    fr = {'closed': N}
    for s, (sx, sy) in SCALE.items():
        if s == 'wide_i':
            fr[s] = put(N, ZONE0, open_ink(sx, sy, CX, CY + 0.5))
        else:  # identical to make_mouths.py v3.4
            fr[s] = put(N, ZONE0, open_ink(sx, sy))
    # closed smile: Alex's pet smile, shrunk to the neutral lip width
    fr['smile'] = put(N, ZONE0, smile_ink(0.72, 0.8, 101.0, 149.0))
    return BOX0, fr

def other_set(base_name, cx, cy, rx, ry, rects, vscale, box):
    B = L(base_name)
    z = ((ZX - cx) / rx) ** 2 + ((ZY - cy) / ry) ** 2 <= 1.0
    for (x0, y0, x1, y1) in rects: z |= (ZX >= x0) & (ZX < x1) & (ZY >= y0) & (ZY < y1)
    Z = blur(z)
    fr = {'closed': B, 'smile': B}
    for s, (sx, sy) in SCALE.items():
        fr[s] = put(B, Z, open_ink(sx, sy * vscale, cx, cy))
    return box, fr

SETS = {
    'neutral': neutral_set(),
    #               base         cx     cy     rx  ry  extra erase rects          vscale  box (x0,y0,x1,y1)
    'sad':      other_set('sad_00',      104.5, 153.5, 12, 8, [(100, 158, 107, 162)], 0.85, (90, 140, 120, 166)),
    'thinking': other_set('thinking_00', 103.0, 147.5, 12, 6, [(95, 150, 102, 154)], 0.72, (90, 136, 118, 156)),
    'pet':      other_set('pet_00',      110.0, 149.0, 16, 8, [(117, 139, 130, 148), (100, 152, 111, 157)], 0.8, (94, 137, 130, 159)),
}

os.makedirs(f'{OUT}/preview', exist_ok=True)
lines = ['// generated by make_mouths_v35.py (headphone-girl v3.5 lip sync). Do not edit.',
         '#pragma once', '#include <stdint.h>',
         '// frame index: 0 closed, 1 half, 2 open(A), 3 wide_e(E), 4 round_o(O), 5 small_u(U), 6 wide_i(I), 7 smile',
         '#define HG_MOUTH_COUNT 8']
setinfo = []
total = 0
for name, (box, fr) in SETS.items():
    x0, y0, x1, y1 = box; w, h = x1 - x0, y1 - y0
    names = []
    seen = {}
    for s in SHAPES:
        c = fr[s].crop(box).convert('RGB')
        key = c.tobytes()
        if key in seen:           # identical frame: reuse the array
            names.append(seen[key]); continue
        px = np.array(c).astype(int)
        v = ((px[:, :, 0] >> 3) << 11) | ((px[:, :, 1] >> 2) << 5) | (px[:, :, 2] >> 3)
        by = []
        for val in v.flatten(): by += [val & 0xff, val >> 8]
        an = f'hg_mouth_{name}_{s}'
        lines.append(f'static const uint8_t {an}[{len(by)}] = {{{",".join(map(str, by))}}};')
        total += len(by)
        names.append(an); seen[key] = an
    lines.append(f'static const uint8_t* const hg_mouth_{name}[HG_MOUTH_COUNT] = {{{",".join(names)}}};')
    setinfo.append((name, x0, y0, w, h))
lines.append('struct HgMouthSet { const char* gif; int x, y, w, h; const uint8_t* const* frames; };')
lines.append('static const HgMouthSet hg_mouth_sets[] = {')
for name, x0, y0, w, h in setinfo:
    gif = {'neutral': 'neutral', 'sad': 'sad', 'thinking': 'thinking', 'pet': 'pet'}[name]
    lines.append(f'    {{"{gif}", {x0}, {y0}, {w}, {h}, hg_mouth_{name}}},')
lines.append('};')
lines.append(f'#define HG_MOUTH_SET_COUNT {len(setinfo)}')
lines.append(f'// total pixel bytes: {total}')
open(f'{OUT}/hg_mouth_frames.h', 'w').write('\n'.join(lines) + '\n')
json.dump({'sets': {n: {'box': SETS[n][0]} for n in SETS}, 'shapes': SHAPES}, open(f'{OUT}/mouths_v35.json', 'w'), indent=1)

# previews: per set, 8 zoomed crops in the real face context
Z = 4
for name, (box, fr) in SETS.items():
    x0, y0, x1, y1 = box
    pad = 14
    cx0, cy0, cx1, cy1 = x0 - pad, y0 - pad, x1 + pad, y1 + pad
    cw, ch = (cx1 - cx0) * Z, (cy1 - cy0) * Z
    sheet = Image.new('RGB', (cw * 4 + 30, (ch + 18) * 2), 'white')
    d = ImageDraw.Draw(sheet)
    for i, s in enumerate(SHAPES):
        c = fr[s].crop((cx0, cy0, cx1, cy1)).resize((cw, ch), Image.NEAREST).convert('RGB')
        dd = ImageDraw.Draw(c); dd.rectangle(((x0 - cx0) * Z, (y0 - cy0) * Z, (x1 - cx0) * Z - 1, (y1 - cy0) * Z - 1), outline=(255, 170, 170))
        px, py = (i % 4) * (cw + 10), (i // 4) * (ch + 18)
        sheet.paste(c, (px, py + 16)); d.text((px + 2, py + 2), f'{i} {s}', fill='black')
    sheet.save(f'{OUT}/preview/mouths_{name}.png')
# full-face sheet: every set with closed / A / I / smile
sel = ['closed', 'open', 'wide_i', 'smile', 'round_o', 'wide_e']
sheet = Image.new('RGB', (W * len(sel) // 2, H * len(SETS) // 2 + 0), 'white')
for r, (name, (box, fr)) in enumerate(SETS.items()):
    for c, s in enumerate(sel):
        sheet.paste(fr[s].convert('RGB').resize((W // 2, H // 2), Image.LANCZOS), (c * W // 2, r * H // 2))
sheet.save(f'{OUT}/preview/faces_all_sets.png')
print('ok, pixel bytes', total)
