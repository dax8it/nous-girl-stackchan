#!/usr/bin/env python3
"""Fit Harper vowel centers (F1/F2 medians) from hand-marked steady segments.
Each clip says the vowel at the start and at the end ("Ahhh. Father calm. Ahhh.").
seg 'A' = first sustained vowel, seg 'B' = last one. Train on one, test on the other.
Input: raw.tsv from ./dump (file, t, rms, f1, f2, voicing, vowel, conf)."""
import csv, statistics, sys, json
SEG = {  # clip: (vowel index 0..4 = a i u e o, [segA], [segB])
 'v1': (0, (0.12, 0.46), (2.22, 2.46)),
 'v2': (1, (0.14, 0.42), (1.70, 1.94)),
 'v3': (2, (0.24, 0.46), (2.10, 2.20)),
 'v4': (3, (0.16, 0.30), (2.12, 2.36)),
 'v5': (4, (0.14, 0.40), (1.84, 1.96)),
}
rows = [r for r in csv.reader(open(sys.argv[1] if len(sys.argv) > 1 else 'raw.tsv'), delimiter='\t')]
def pts(clip, seg):
    out = []
    for r in rows:
        if not r[0].endswith(clip + '.wav'): continue
        t, f1, f2, v = float(r[1]), float(r[3]), float(r[4]), float(r[5])
        if seg[0] <= t <= seg[1] and f1 > 0 and f2 > 0 and v >= 0.55: out.append((f1, f2))
    return out
def fit(which):
    f1 = [0]*5; f2 = [0]*5
    for clip, (vi, a, b) in SEG.items():
        p = pts(clip, a) if which == 'A' else pts(clip, b) if which == 'B' else pts(clip, a) + pts(clip, b)
        f1[vi] = round(statistics.median(x for x, _ in p)); f2[vi] = round(statistics.median(y for _, y in p))
    return f1, f2
res = {w: fit(w) for w in ('A', 'B', 'AB')}
json.dump(res, open('fit.json', 'w'))
for w, (f1, f2) in res.items(): print(w, 'f1', f1, 'f2', f2)
f1, f2 = res['AB']
open('../../xiaozhi-esp32-build/main/audio/hg_vowel_model.inc', 'w').write(
 '// generated by build/lipsync/v35/calibrate.py from Phonon Harper sustained vowels. Do not edit.\n'
 '// order: a, i, u, e, o\n'
 f'inline constexpr VowelModel kHarperModel{{{{{", ".join(map(str, f1))}}}, {{{", ".join(map(str, f2))}}}, 35}};\n')
print('wrote hg_vowel_model.inc')
